import { describe, it, expect } from 'vitest'
import { mountSuspended } from '@nuxt/test-utils/runtime'
import MestoApp from '../../app/components/MestoApp.vue'
import { useDemoStore } from '../../app/stores/demo.js'
import { nextTick } from 'vue'

describe('guest search filters', () => {
  it('dismisses the map card and restores it when another marker is selected', async () => {
    localStorage.clear()
    const wrapper = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.$reset(); store.restore(); await nextTick()
    expect(wrapper.find('.map-card').exists()).toBe(false)
    wrapper.findComponent({ name: 'YandexMap' }).vm.$emit('select', 'p1')
    await nextTick()
    expect(wrapper.find('.map-card').exists()).toBe(true)
    await wrapper.get('[aria-label="Закрыть карточку объекта"]').trigger('click')
    expect(store.selectedPropertyId).toBeNull()
    expect(wrapper.find('.map-card').exists()).toBe(false)
    wrapper.findComponent({ name: 'YandexMap' }).vm.$emit('select', 'p1')
    await nextTick()
    expect(wrapper.find('.map-card').exists()).toBe(true)
    wrapper.findComponent({ name: 'YandexMap' }).vm.$emit('select', null)
    await nextTick()
    expect(wrapper.find('.map-card').exists()).toBe(false)
    wrapper.unmount()
  })
  it('opens inland city pages without the reference sea-view filter', async () => {
    localStorage.clear()
    const wrapper = await mountSuspended(MestoApp, { route: '/locations/krasnodar', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.$reset(); store.restore(); await nextTick()
    expect(wrapper.findAll('.property-card').length).toBeGreaterThan(0)
    expect(wrapper.findAll('.property-card').every(card => card.text().includes('Краснодар'))).toBe(true)
    wrapper.unmount()
    const filtered = await mountSuspended(MestoApp, { route: '/locations/krasnodar?amenities=sea_view', global: { stubs: { YandexMap: true } } })
    expect(filtered.findAll('.property-card')).toHaveLength(0)
    filtered.unmount()
  })
  it('keeps the demo error across screen remounts and supports retry', async () => {
    localStorage.clear()
    const profile = await mountSuspended(MestoApp, { route: '/profile', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.$reset(); store.restore(); await nextTick()
    await profile.findAll('button').find(button => button.text() === 'Показать ошибку')!.trigger('click')
    profile.unmount()
    const search = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    expect(search.text()).toContain('Не удалось загрузить варианты')
    await search.findAll('button').find(button => button.text() === 'Попробовать ещё раз')!.trigger('click')
    expect(store.scenario).toBe('normal')
    expect(search.find('.property-card').exists()).toBe(true)
    search.unmount()
  })
  it('keeps map selection and list mode when returning to search', async () => {
    localStorage.clear()
    const first = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.$reset(); store.restore()
    store.setFilters({ checkIn: '2027-06-12', checkOut: '2027-06-16', guests: 2, maxPrice: null, amenities: [] })
    first.unmount()
    const search = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    search.findComponent({ name: 'YandexMap' }).vm.$emit('select', 'p1')
    await nextTick()
    await search.get('[aria-label="Следующий объект"]').trigger('click')
    expect(store.selectedPropertyId).toBe('p2')
    await search.findAll('button').find(button => button.text().includes('Список'))!.trigger('click')
    search.unmount()
    const returned = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    expect(store.mapMode).toBe(false)
    expect(returned.get('.map-card').text()).toContain('Кипарис')
    returned.unmount()
  })
  it('applies a price filter and resets it through the screen', async () => {
    localStorage.clear()
    const wrapper = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.restore()
    await nextTick()
    const filters = wrapper.findAll('button').find(button => button.text().includes('Фильтры'))!
    await filters.trigger('click')
    await wrapper.get('input[placeholder="Без ограничений"]').setValue('500')
    const apply = wrapper.findAll('button').find(button => button.text() === 'Показать варианты')!
    await apply.trigger('click')
    await nextTick()
    expect(wrapper.findAll('.property-card')).toHaveLength(0)
    expect(store.data!.filters.maxPrice).toBe(500)
    const reset = wrapper.findAll('button').find(button => button.text() === 'Сбросить фильтры')!
    await reset.trigger('click')
    await nextTick()
    expect(store.data!.filters.maxPrice).toBeNull()
    expect(store.data!.filters.amenities).toEqual([])
    expect(wrapper.findAll('.property-card').length).toBeGreaterThan(1)
    wrapper.unmount()
  })
})
