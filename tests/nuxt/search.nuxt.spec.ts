import { flushPromises } from '@vue/test-utils'
import { describe, it, expect } from 'vitest'
import { mountSuspended } from '@nuxt/test-utils/runtime'
import MestoApp from '../../app/components/MestoApp.vue'
import { useDemoStore } from '../../app/stores/demo.js'
import { nextTick } from 'vue'

describe('guest search filters', () => {
  it('dismisses the map card and restores it when another marker is selected', async () => {
    localStorage.clear()
    const wrapper = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.$reset(); store.restore(); await nextTick()
    expect(wrapper.findAll('.property-card').length).toBeGreaterThan(20)
    expect(wrapper.findAll('.desktop-chip.selected')).toHaveLength(0)
    expect(wrapper.findAll('button').find(button => button.text().includes('Все фильтры'))!.text()).not.toContain('·')
    expect(wrapper.find('.map-card').exists()).toBe(false)
    wrapper.findComponent({ name: 'YandexMap' }).vm.$emit('select', 'p1')
    await nextTick()
    expect(wrapper.find('.map-card').exists()).toBe(true)
    await wrapper.get('[aria-label="Закрыть карточку объекта"]').trigger('click')
    expect(store.selectedPropertyId).toBeNull()
    expect(wrapper.find('.map-card').exists()).toBe(false)
    wrapper.findComponent({ name: 'YandexMap' }).vm.$emit('select', 'p1')
    await nextTick()
    expect(wrapper.find('.map-card').exists()).toBe(true)
    wrapper.findComponent({ name: 'YandexMap' }).vm.$emit('select', null)
    await nextTick()
    expect(wrapper.find('.map-card').exists()).toBe(false)
    await flushPromises()
    wrapper.unmount()
  })
  it('opens inland city pages without the reference sea-view filter', async () => {
    localStorage.clear()
    const wrapper = await mountSuspended(MestoApp, { route: '/locations/krasnodar', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.$reset(); store.restore(); await nextTick()
    expect(wrapper.findAll('.property-card').length).toBeGreaterThan(0)
    expect(wrapper.findAll('.property-card').every(card => card.text().includes('Краснодар'))).toBe(true)
    await flushPromises()
    wrapper.unmount()
    const filtered = await mountSuspended(MestoApp, { route: '/locations/krasnodar?amenities=sea_view', global: { stubs: { YandexMap: true } } })
    expect(filtered.findAll('.property-card')).toHaveLength(0)
    filtered.unmount()
  })
  it('keeps the demo error across screen remounts and supports retry', async () => {
    localStorage.clear()
    const profile = await mountSuspended(MestoApp, { route: '/profile', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.$reset(); store.restore(); await nextTick()
    await profile.findAll('button').find(button => button.text() === 'Показать ошибку')!.trigger('click')
    profile.unmount()
    const search = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    expect(search.text()).toContain('Не удалось загрузить варианты')
    await search.findAll('button').find(button => button.text() === 'Попробовать ещё раз')!.trigger('click')
    expect(store.scenario).toBe('normal')
    expect(search.find('.property-card').exists()).toBe(true)
    await flushPromises()
    search.unmount()
  })
  it('keeps map selection and list mode when returning to search', async () => {
    localStorage.clear()
    const first = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.$reset(); store.restore()
    store.setFilters({ checkIn: '2027-06-12', checkOut: '2027-06-16', guests: 2, maxPrice: null, amenities: [] })
    first.unmount()
    const search = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    search.findComponent({ name: 'YandexMap' }).vm.$emit('select', 'p1')
    await nextTick()
    await search.get('[aria-label="Следующий объект"]').trigger('click')
    expect(store.selectedPropertyId).toBe('p2')
    await search.findAll('button').find(button => button.text().includes('Список'))!.trigger('click')
    await flushPromises()
    search.unmount()
    const returned = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    expect(store.mapMode).toBe(false)
    expect(returned.get('.map-card').text()).toContain('Кипарис')
    returned.unmount()
  })
  it('applies a price filter and resets it through the screen', async () => {
    localStorage.clear()
    const wrapper = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.restore()
    await nextTick()
    const filters = wrapper.findAll('button').find(button => button.text().includes('Все фильтры'))!
    expect(wrapper.get('.search-controls').findAll('button').at(-1)!.text()).toContain('Все фильтры')
    await filters.trigger('click')
    expect(filters.attributes('aria-expanded')).toBe('true')
    expect(wrapper.find('#search-editor').exists()).toBe(true)
    expect(wrapper.find('[role=dialog]').exists()).toBe(false)
    await filters.trigger('click')
    expect(wrapper.find('#search-editor').exists()).toBe(false)
    await filters.trigger('click')
    await wrapper.get('input[placeholder="Без ограничений"]').setValue('500')
    expect(wrapper.findAll('.property-card').length).toBeGreaterThan(1)
    expect(store.data!.filters.maxPrice).toBeNull()
    const apply = wrapper.findAll('button').find(button => button.text().startsWith('Показать '))!
    await apply.trigger('click')
    await nextTick()
    expect(wrapper.findAll('.property-card')).toHaveLength(0)
    expect(store.data!.filters.maxPrice).toBe(500)
    const reset = wrapper.findAll('button').find(button => button.text() === 'Сбросить фильтры')!
    await reset.trigger('click')
    await nextTick()
    expect(store.data!.filters.maxPrice).toBeNull()
    expect(store.data!.filters.amenities).toEqual([])
    expect(wrapper.findAll('.property-card').length).toBeGreaterThan(1)
    await flushPromises()
    wrapper.unmount()
  })
  it('discards price edits when the panel is closed and normalizes an empty price', async () => {
    localStorage.clear()
    const wrapper = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.$reset(); store.restore(); await nextTick()
    const open = () => wrapper.get('[data-search-panel="filters"]').trigger('click')
    await open()
    await wrapper.get('[name=maxPrice]').setValue('500')
    await wrapper.get('[aria-label="Закрыть без применения"]').trigger('click')
    expect(store.data!.filters.maxPrice).toBeNull()
    await open()
    expect(wrapper.get<HTMLInputElement>('[name=maxPrice]').element.value).toBe('')
    await wrapper.get('[name=maxPrice]').setValue('500')
    await wrapper.get('[name=maxPrice]').setValue('')
    await wrapper.get('.filter-actions .primary').trigger('click')
    expect(store.data!.filters.maxPrice).toBeNull()
    expect(wrapper.findAll('.property-card').length).toBeGreaterThan(1)
    await flushPromises()
    wrapper.unmount()
  })
  it('edits dates inline, rejects invalid ranges, and keeps the applied trip until confirmation', async () => {
    localStorage.clear()
    const wrapper = await mountSuspended(MestoApp, { route: '/search', global: { stubs: { YandexMap: true } } } )
    const store = useDemoStore(); store.$reset(); store.restore(); await nextTick()
    await wrapper.get('[data-search-panel="dates"]').trigger('click')
    expect(wrapper.find('[role=dialog]').exists()).toBe(false)
    await wrapper.get('[name=checkOut]').setValue('2027-06-11')
    await wrapper.get('.filter-actions .primary').trigger('click')
    expect(wrapper.get('[role=alert]').text()).toContain('Выезд должен быть позже заезда')
    expect(wrapper.get('[name=checkOut]').attributes('aria-invalid')).toBe('true')
    expect(store.data!.filters.checkOut).toBe('2027-06-16')
    await wrapper.get('[name=checkOut]').setValue('2027-06-19')
    await wrapper.get('.filter-actions .primary').trigger('click')
    expect(store.data!.filters.checkOut).toBe('2027-06-19')
    await flushPromises()
    wrapper.unmount()
  })
  it('restores the previous dates when today is toggled off', async () => {
    localStorage.clear()
    const wrapper = await mountSuspended(MestoApp, { route: '/search?checkIn=2027-06-18&checkOut=2027-06-22', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.$reset(); store.restore(); await nextTick()
    const today = wrapper.findAll('button').find(b => b.text() === 'Заезд сегодня')!
    await today.trigger('click')
    expect(store.data!.filters).toMatchObject({ checkIn: '2027-06-12', checkOut: '2027-06-13' })
    expect(today.attributes('aria-pressed')).toBe('true')
    await today.trigger('click')
    expect(store.data!.filters).toMatchObject({ checkIn: '2027-06-18', checkOut: '2027-06-22' })
    expect(today.attributes('aria-pressed')).toBe('false')
    await flushPromises()
    wrapper.unmount()
  })
  it('clears restrictions without changing the trip or destination', async () => {
    localStorage.clear()
    const wrapper = await mountSuspended(MestoApp, { route: '/search?city=Ялта&checkIn=2027-06-18&checkOut=2027-06-22&guests=3&maxPrice=500', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.$reset(); store.restore(); await nextTick()
    await wrapper.findAll('button').find(b => b.text() === 'Сбросить ограничения')!.trigger('click')
    expect(store.data!.filters).toMatchObject({ city: 'Ялта', checkIn: '2027-06-18', checkOut: '2027-06-22', guests: 3, maxPrice: null })
    await flushPromises()
    wrapper.unmount()
  })
  it('keeps the budget when listing units on a property page', async () => {
    localStorage.clear()
    const wrapper = await mountSuspended(MestoApp, { route: '/stays/p2?maxPrice=4000', global: { stubs: { YandexMap: true } } })
    const store = useDemoStore(); store.$reset(); store.restore(); await nextTick()
    expect(wrapper.findAll('button.unit-row').length).toBeGreaterThan(0)
    expect(wrapper.findAll('button.unit-row').map(row => row.text())).not.toEqual(expect.arrayContaining([expect.stringContaining('5 600'), expect.stringContaining('6 800')]))
    await flushPromises()
    wrapper.unmount()
  })

})
